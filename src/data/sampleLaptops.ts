export const SAMPLE_LAPTOPS_MAP: Record<string, Product> = {};

SAMPLE_LAPTOPS.forEach((l) => {
  SAMPLE_LAPTOPS_MAP[l.id] = l;
});

export function findSampleLaptopById(id: string): Product | undefined {
  if (!id) return undefined;
  if (SAMPLE_LAPTOPS_MAP[id]) return SAMPLE_LAPTOPS_MAP[id];

  const lowerId = id.toLowerCase();
  for (const [k, p] of Object.entries(SAMPLE_LAPTOPS_MAP)) {
    if (k.toLowerCase() === lowerId) return p;
  }

  for (const p of SAMPLE_LAPTOPS) {
    const normModel = p.model.toLowerCase().replace(/[^a-z0-9]/g, '');
    const normId = lowerId.replace(/[^a-z0-9]/g, '');
    if (normId.includes(normModel) || normModel.includes(normId)) {
      return p;
    }
  }

  return undefined;
}

