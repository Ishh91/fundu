/**
 * Universal Indian phone model lookup / search helper
 */
export function searchIndianPhones(query: string, brand?: string, limit = 50): MasterPhone[] {
  let list = ALL_INDIAN_PHONES_CATALOG;
  if (brand && brand.toLowerCase() !== 'all') {
    list = list.filter((p) => p.brand.toLowerCase() === brand.toLowerCase());
  }

  if (!query || !query.trim()) {
    return list.slice(0, limit);
  }

  const q = query.toLowerCase().trim();
  return list
    .filter((p) => {
      const fullText = `${p.brand} ${p.model} ${p.release_year} ${p.popular_tag || ''} ${p.processor || ''}`.toLowerCase();
      return fullText.includes(q);
    })
    .slice(0, limit);
}

/**
 * Get phone details by model name
 */
export function getIndianPhoneByModel(modelName: string): MasterPhone | undefined {
  const norm = modelName.toLowerCase().trim();
  return ALL_INDIAN_PHONES_CATALOG.find((p) => `${p.brand} ${p.model}`.toLowerCase() === norm || p.model.toLowerCase() === norm);
}
