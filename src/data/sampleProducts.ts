export function findSampleProductById(id: string): Product | undefined {
  if (!id) return undefined;
  if (SAMPLE_PRODUCTS_MAP[id]) return SAMPLE_PRODUCTS_MAP[id];
  
  // Try case-insensitive matching
  const lowerId = id.toLowerCase();
  for (const [k, p] of Object.entries(SAMPLE_PRODUCTS_MAP)) {
    if (k.toLowerCase() === lowerId) return p;
  }

  // Try matching by title or model in the id
  for (const p of SAMPLE_BEST_SELLING_PHONES) {
    const normModel = p.model.toLowerCase().replace(/[^a-z0-9]/g, '');
    const normTitle = p.title.toLowerCase().replace(/[^a-z0-9]/g, '');
    const normId = lowerId.replace(/[^a-z0-9]/g, '');
    if (normId.includes(normModel) || normTitle.includes(normId)) {
      return p;
    }
  }

  return undefined;
}
