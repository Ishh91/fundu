export function getLocalPhoneById(id: string): PhoneItem | undefined {
  return phonesData.find((p) => p.id === id || p.id.toLowerCase() === id.toLowerCase());
}

export function searchLocalPhones(query: string): PhoneItem[] {
  if (!query || query.trim().length === 0) return phonesData;
  const q = query.toLowerCase().trim();
  return phonesData.filter(
    (p) =>
      p.brand.toLowerCase().includes(q) ||
      p.model.toLowerCase().includes(q) ||
      `${p.brand} ${p.model}`.toLowerCase().includes(q)
  );
}

export function getLocalPhonesByBrand(brand: string): PhoneItem[] {
  if (!brand || brand.toLowerCase() === 'all') return phonesData;
  const b = brand.toLowerCase().trim();
  return phonesData.filter((p) => p.brand.toLowerCase() === b);
}
