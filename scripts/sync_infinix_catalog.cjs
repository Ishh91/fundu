async function syncAll() {
  console.log(`Starting synchronization for ${infinixModels.length} Infinix models...`);

  // 1. UPDATE server/config/phonesCatalog.json
  const phonesCatalogPath = path.join(__dirname, '../server/config/phonesCatalog.json');
  if (fs.existsSync(phonesCatalogPath)) {
    let catalog = JSON.parse(fs.readFileSync(phonesCatalogPath, 'utf8'));
    // Remove old sparse Infinix models to avoid duplicates
    const nonInfinix = catalog.filter(p => (p.brand || '').toLowerCase() !== 'infinix');
    
    // Format Infinix models for phonesCatalog.json
    const formattedInfinix = infinixModels.map(item => {
      let cleanModel = item.model.trim();
      if (cleanModel.toLowerCase().startsWith('infinix')) {
        cleanModel = cleanModel.slice(7).trim();
      }
      return {
        brand: 'Infinix',
        model: cleanModel,
        release_year: item.release_year,
        ram_options: item.ram_options,
        storage_options: item.storage_options,
        default_mrp: item.default_mrp,
        base_resale_value: item.base_resale_value,
        price: item.price,
        popular_tag: `${item.series}`,
        image_url: item.image_url,
        processor: item.processor,
        camera_spec: item.camera_spec,
        battery_spec: item.battery_spec,
        display_spec: item.display_spec,
        is_5g: item.is_5g,
        is_active: true
      };
    });

    const merged = [...nonInfinix, ...formattedInfinix];
    fs.writeFileSync(phonesCatalogPath, JSON.stringify(merged, null, 2), 'utf8');
    console.log(`✅ phonesCatalog.json updated: Total ${merged.length} models (${formattedInfinix.length} Infinix models).`);
  }

  // 2. UPDATE src/data/deviceImageDictionary.ts
  const dictPath = path.join(__dirname, '../src/data/deviceImageDictionary.ts');
  if (fs.existsSync(dictPath)) {
    let dictContent = fs.readFileSync(dictPath, 'utf8');
    let addedImages = 0;
    infinixModels.forEach(item => {
      const cleanModel = item.model.toLowerCase().replace(/^infinix\s+/i, '').trim();
      const key1 = `infinix ${cleanModel}`;
      const key2 = cleanModel;
      if (!dictContent.includes(`"${key1}":`)) {
        const line = `  "${key1}": "${item.image_url}",\n`;
        dictContent = dictContent.replace('export const DEVICE_IMAGE_DICTIONARY: Record<string, string> = {', `export const DEVICE_IMAGE_DICTIONARY: Record<string, string> = {\n${line}`);
        addedImages++;
      }
    });
    fs.writeFileSync(dictPath, dictContent, 'utf8');
    console.log(`✅ deviceImageDictionary.ts updated: Added ${addedImages} Infinix image mappings.`);
  }

  // 3. UPDATE MongoDB masterphones collection
  if (process.env.MONGODB_URI) {
    try {
      console.log('Connecting to MongoDB...');
      await mongoose.connect(process.env.MONGODB_URI, {
        dbName: process.env.MONGODB_DB_NAME || 'fundu',
        tls: true,
        tlsAllowInvalidCertificates: true,
        serverSelectionTimeoutMS: 8000,
      });

      const db = mongoose.connection.db;
      const collection = db.collection('masterphones');

      let upsertedCount = 0;
      for (const item of infinixModels) {
        let cleanModel = item.model.trim();
        if (cleanModel.toLowerCase().startsWith('infinix')) {
          cleanModel = cleanModel.slice(7).trim();
        }

        const filter = {
          brand: 'Infinix',
          $or: [
            { model: cleanModel },
            { model: item.model },
            { model: new RegExp(`^${cleanModel}$`, 'i') }
          ]
        };

        const updateDoc = {
          $set: {
            brand: 'Infinix',
            model: cleanModel,
            release_year: item.release_year,
            ram_options: item.ram_options,
            storage_options: item.storage_options,
            default_mrp: item.default_mrp,
            base_resale_value: item.base_resale_value,
            price: item.price,
            popular_tag: item.series,
            image_url: item.image_url,
            processor: item.processor,
            camera_spec: item.camera_spec,
            battery_spec: item.battery_spec,
            display_spec: item.display_spec,
            is_5g: item.is_5g,
            is_active: true,
            updated_at: new Date()
          }
        };

        await collection.updateOne(filter, updateDoc, { upsert: true });
        upsertedCount++;
      }

      console.log(`✅ MongoDB: Successfully upserted ${upsertedCount} Infinix models into masterphones collection!`);
      await mongoose.disconnect();
    } catch (err) {
      console.warn('MongoDB sync notice (will be seeded on next Render start):', err.message);
    }
  }

  console.log('Infinix synchronization complete!');
}

syncAll().catch(console.error);

